  GetAnalysis,
  MatchAnalysisSources,
  GetFolderVisibility,
  ListTemplateFolders,
  SetHiddenFolderNames,
  SetShowHiddenFolders,
  SetFolderOverride,
  GetDraftSection,
  SetDraftSection,
  CreateWritingSeries,
  CreateWritingBook,
  RenameWritingProject,
  DeleteWritingProject,
  ReadDiskFile,
  WriteDiskFile,
