  GetUISession,
  SetUISelection,
  ToggleOpenSeries,
  ToggleOpenStory,
  ToggleOpenFolder,
  EnsureOpenSeries,
  EnsureOpenStory,
  EnsureOpenFolder,
  SetRestoreOpen,
  SetLastPen,
  ListWritingTree,
